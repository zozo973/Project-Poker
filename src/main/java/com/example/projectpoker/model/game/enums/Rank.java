package com.example.projectpoker.model.game.enums;

/**
 * Enumeration of playing card ranks from Two through Ace.
 * Used in combination with {@link Suit} to define individual cards.
 * Ordinal values: Two=0, Three=1, ..., Ace=12.
 */
public enum Rank {
    /** Rank value 2. */
    Two,
    /** Rank value 3. */
    Three,
    /** Rank value 4. */
    Four,
    /** Rank value 5. */
    Five,
    /** Rank value 6. */
    Six,
    /** Rank value 7. */
    Seven,
    /** Rank value 8. */
    Eight,
    /** Rank value 9. */
    Nine,
    /** Rank value 10. */
    Ten,
    /** Rank value 11. */
    Jack,
    /** Rank value 12. */
    Queen,
    /** Rank value 13. */
    King,
    /** Rank value 14 (highest). */
    Ace;
}
