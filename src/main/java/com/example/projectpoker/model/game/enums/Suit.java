package com.example.projectpoker.model.game.enums;

/**
 * Enumeration of card suits used in standard playing cards.
 * Used in combination with {@link Rank} to define individual cards.
 */
public enum Suit {
    /** Spades suit. */
    Spades,
    /** Clubs suit. */
    Clubs,
    /** Hearts suit. */
    Hearts,
    /** Diamonds suit. */
    Diamonds;
}